SOURCE_SHA = re.compile(r"^[0-9a-f]{40}$")
SHA256 = re.compile(r"^[0-9a-f]{64}$")
SRI = re.compile(r"^(sha256|sha512)-([A-Za-z0-9+/]+={0,2})$")
PACKAGE_NAME = re.compile(r"^[A-Za-z0-9@._/+~-]+$")
LICENSE_BASENAME = re.compile(
    r"^(?:licen[cs]e|copying|copyright|notice|authors?)(?:[._-].*)?$", re.I
)
SPDX_TOKEN = re.compile(r"\b[A-Za-z0-9][A-Za-z0-9.+-]*\b")
LICENSE_OPERATORS = {"AND", "OR", "WITH"}


class ReleaseError(RuntimeError):
    """A fail-closed compliance validation error."""


def canonical_json(value: Any) -> bytes:
    return json.dumps(
        value, ensure_ascii=False, separators=(",", ":"), sort_keys=True
    ).encode("utf-8")


def sha256_bytes(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def normalized_name(value: str) -> str:
    return re.sub(r"[-_.]+", "-", value).lower()


def safe_slug(value: str) -> str:
    slug = urllib.parse.quote(value, safe="-._@+")
    if not slug or slug in {".", ".."}:
        raise ReleaseError(f"unsafe empty artifact slug: {value!r}")
    return slug


def validate_relative_path(value: str) -> PurePosixPath:
    if not value or "\\" in value or value.startswith(("/", "./")) or "//" in value:
        raise ReleaseError(f"invalid relative POSIX path: {value!r}")
    path = PurePosixPath(value)
    if any(part in {"", ".", ".."} for part in path.parts):
        raise ReleaseError(f"unsafe relative path: {value!r}")
    return path


def parse_integrity(value: str) -> tuple[str, bytes]:
    match = SRI.fullmatch(value)
    if match is None:
        raise ReleaseError(f"unsupported integrity value: {value!r}")
    try:
        expected = base64.b64decode(match.group(2), validate=True)
    except ValueError as error:
        raise ReleaseError(f"invalid integrity encoding: {value!r}") from error
    return match.group(1), expected


def verify_integrity(payload: bytes, integrity: str) -> None:
    algorithm, expected = parse_integrity(integrity)
    actual = hashlib.new(algorithm, payload).digest()
    if actual != expected:
        raise ReleaseError(f"artifact digest differs from {integrity}")


def npm_archive_url(name: str, version: str) -> str:
    if not PACKAGE_NAME.fullmatch(name) or not PACKAGE_NAME.fullmatch(version):
        raise ReleaseError(f"unsafe npm identity: {name}@{version}")
    basename = name.rsplit("/", 1)[-1]
    return f"https://registry.npmjs.org/{name}/-/{basename}-{version}.tgz"


def build_checksum_manifest(directory: Path) -> bytes:
    files = []
    for path in directory.rglob("*"):
        if path.is_symlink() or not path.is_file():
            continue
        relative = path.relative_to(directory).as_posix()
        if relative == "SHA256SUMS":
            continue
        files.append((relative, path))
    entries = [
        f"{sha256_file(path)}  {relative}\n"
        for relative, path in sorted(files, key=lambda item: item[0])
    ]
    return "".join(entries).encode("utf-8")


def parse_checksum_manifest(payload: bytes) -> dict[str, str]:
    result: dict[str, str] = {}
    previous = ""
    for line in payload.decode("utf-8").splitlines():
        match = re.fullmatch(r"([0-9a-f]{64})  (.+)", line)
        if match is None:
            raise ReleaseError("SHA256SUMS has a malformed line")
        relative = match.group(2)
        validate_relative_path(relative)
        if relative <= previous or relative in result or relative == "SHA256SUMS":
            raise ReleaseError("SHA256SUMS is not unique and strictly sorted")
        previous = relative
        result[relative] = match.group(1)
    if not result:
        raise ReleaseError("SHA256SUMS is empty")
    return result


class CommandRunner(Protocol):
    def run(
        self, arguments: Sequence[str], *, cwd: Path | None = None, text: bool = True
    ) -> str | bytes: ...


class SubprocessRunner:
    def run(
        self, arguments: Sequence[str], *, cwd: Path | None = None, text: bool = True
    ) -> str | bytes:
        try:
            return subprocess.run(
                list(arguments),
                cwd=cwd,
                check=True,
                capture_output=True,
                text=text,
            ).stdout
        except (OSError, subprocess.CalledProcessError) as error:
            stderr = getattr(error, "stderr", "")
            if isinstance(stderr, bytes):
                stderr = stderr.decode("utf-8", errors="replace")
            raise ReleaseError(
                f"command failed: {' '.join(arguments)}: {str(stderr).strip()}"
            ) from error


def normalize_origin(value: str) -> str:
    value = value.strip().removesuffix("/")
    if value.startswith("git@github.com:"):
        value = "https://github.com/" + value.removeprefix("git@github.com:")
    if value.startswith("git+https://"):
        value = value.removeprefix("git+")
    return value


@dataclass(frozen=True)
class GitProvenance:
    commit: str
    tree: str
    parents: tuple[str, ...]
    commit_timestamp: int
    origin: str
    live_refs: tuple[str, ...]
    commit_object_sha256: str


class GitRepository:
    def __init__(self, path: Path, runner: CommandRunner | None = None) -> None:
        self.path = path.resolve()
        self.runner = runner or SubprocessRunner()

    def git(self, *arguments: str, text: bool = True) -> str | bytes:
        return self.runner.run(("git", *arguments), cwd=self.path, text=text)

    def exact_root(self) -> Path:
        return Path(str(self.git("rev-parse", "--show-toplevel")).strip()).resolve()

    def head(self) -> str:
        return str(self.git("rev-parse", "HEAD")).strip()

    def branch(self) -> str:
        return str(self.git("branch", "--show-current")).strip()

    def origin(self) -> str:
        return normalize_origin(str(self.git("remote", "get-url", "origin")))

    def is_clean(self) -> bool:
        return not str(self.git("status", "--porcelain=v1", "--untracked-files=all"))

    def object_exists(self, commit: str) -> bool:
        if SOURCE_SHA.fullmatch(commit) is None:
            return False
        try:
            self.git("cat-file", "-e", f"{commit}^{{commit}}")
            return True
        except ReleaseError:
            return False

    def live_refs(self) -> dict[str, str]:
        output = str(self.git("ls-remote", "--heads", "--tags", "origin"))
        refs: dict[str, str] = {}
        for line in output.splitlines():
            sha, separator, name = line.partition("\t")
            if separator and SOURCE_SHA.fullmatch(sha) and not name.endswith("^{}"):
                refs[name] = sha
        if not refs:
            raise ReleaseError(f"origin has no advertised refs: {self.path}")
        return refs

    def refs_containing(self, commit: str, refs: Mapping[str, str]) -> tuple[str, ...]:
        containing = []
        for name, tip in sorted(refs.items()):
            if not self.object_exists(tip):
                continue
            try:
                self.git("merge-base", "--is-ancestor", commit, tip)
            except ReleaseError:
                continue
            containing.append(name)
        return tuple(containing)

    def provenance(self, commit: str, live_refs: Iterable[str]) -> GitProvenance:
        if not self.object_exists(commit):
            raise ReleaseError(f"Git commit is unavailable: {commit}")
        tree = str(self.git("show", "-s", "--format=%T", commit)).strip()
        parents_raw = str(self.git("show", "-s", "--format=%P", commit)).strip()
        timestamp = int(str(self.git("show", "-s", "--format=%ct", commit)).strip())
        raw_commit = self.git("cat-file", "commit", commit, text=False)
        assert isinstance(raw_commit, bytes)
        return GitProvenance(
            commit=commit,
            tree=tree,
            parents=tuple(parents_raw.split()) if parents_raw else (),
            commit_timestamp=timestamp,
            origin=self.origin(),
            live_refs=tuple(sorted(live_refs)),
            commit_object_sha256=sha256_bytes(raw_commit),
        )

    def archive(self, commit: str, prefix: str) -> bytes:
        validate_relative_path(prefix.rstrip("/"))
        tar_payload = self.git(
            "archive", "--format=tar", f"--prefix={prefix}", commit, text=False
        )
        assert isinstance(tar_payload, bytes)
        output = io.BytesIO()
        with gzip.GzipFile(filename="", mode="wb", fileobj=output, mtime=0) as stream:
            stream.write(tar_payload)
        return output.getvalue()


@dataclass(frozen=True)
class VendoredComponent:
    name: str
    version: str
    license_expression: str
    source_url: str
    integrity: str
    relationship: str


@dataclass(frozen=True)
class ReleasePolicy:
    path: Path
    format_name: str
    format_version: int
    repository_origin: str
    integration_branch: str
    integration_commit: str
    release_branch: str
    upstream_origin: str
    upstream_commit_file: str
    mail_edge_origin: str
    mail_edge_commit_file: str
    mail_edge_evidence_file: str
    signed_evidence_status: str
    spdx_origin: str
    spdx_commit: str
    spdx_tag: str
    gitleaks_version: str
    gitleaks_archive_sha256: str
    distribution_scope: Mapping[str, str]
    maximum_download_bytes: int
    maximum_archive_members: int
    maximum_license_bytes: int
    maximum_license_files: int
    secret_fixture_hashes: Mapping[str, str]
    license_reference_texts: Mapping[str, str]
    python_overrides: Mapping[str, str]
    npm_overrides: Mapping[str, str]
    vendored: tuple[VendoredComponent, ...]
    source_assets: tuple[Mapping[str, Any], ...]

    @classmethod
    def load(cls, path: Path) -> "ReleasePolicy":
        with path.open("rb") as stream:
            raw = tomllib.load(stream)
        if raw.get("format_version") != 1:
            raise ReleaseError("unsupported public release policy format")
        repository = raw["repository"]
        mail_edge = raw["mail_edge"]
        spdx = raw["spdx"]
        tooling = raw["tooling"]
        limits = raw["limits"]
        commit_values = (
            repository["integration_commit"],
            spdx["license_list_commit"],
        )
        if any(SOURCE_SHA.fullmatch(value) is None for value in commit_values):
            raise ReleaseError("policy contains a non-exact Git commit")
        if (
            re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+", tooling["gitleaks_version"]) is None
            or SHA256.fullmatch(tooling["gitleaks_darwin_arm64_archive_sha256"]) is None
        ):
            raise ReleaseError("policy contains an invalid Gitleaks pin")
        vendored = tuple(
            VendoredComponent(
                name=item["name"],
                version=item["version"],
                license_expression=item["license_expression"],
                source_url=item["source_url"],
                integrity=item["integrity"],
                relationship=item["relationship"],
            )
            for item in raw.get("vendored_components", [])
        )
        secret_fixture_hashes = dict(
            sorted(raw.get("secret_fixture_sha256", {}).items())
        )
        if len(secret_fixture_hashes) != 7:
            raise ReleaseError("reviewed secret fixture set must contain seven files")
        for relative, digest in secret_fixture_hashes.items():
            validate_relative_path(relative)
            if SHA256.fullmatch(digest) is None:
                raise ReleaseError("reviewed secret fixture hash is invalid")
        license_reference_texts = dict(
            sorted(raw.get("license_reference_texts", {}).items())
        )
        for license_id, license_text in license_reference_texts.items():
            if re.fullmatch(r"LicenseRef-[A-Za-z0-9.-]+", license_id) is None:
                raise ReleaseError("custom license reference ID is invalid")
            if not license_text.strip() or len(license_text.encode()) > int(
                limits["maximum_license_bytes"]
            ):
                raise ReleaseError("custom license reference text is invalid")
        return cls(
            path=path.resolve(),
            format_name=raw["bundle_format"],
            format_version=raw["bundle_format_version"],
            repository_origin=normalize_origin(repository["origin"]),
            integration_branch=repository["integration_branch"],
            integration_commit=repository["integration_commit"],
            release_branch=repository["release_branch"],
            upstream_origin=normalize_origin(repository["upstream_origin"]),
            upstream_commit_file=repository["upstream_commit_file"],
            mail_edge_origin=normalize_origin(mail_edge["origin"]),
            mail_edge_commit_file=mail_edge["default_commit_file"],
            mail_edge_evidence_file=mail_edge["evidence_commit_file"],
            signed_evidence_status=mail_edge["signed_evidence_status"],
            spdx_origin=normalize_origin(spdx["license_list_origin"]),
            spdx_commit=spdx["license_list_commit"],
            spdx_tag=spdx["license_list_tag"],
            gitleaks_version=tooling["gitleaks_version"],
            gitleaks_archive_sha256=tooling["gitleaks_darwin_arm64_archive_sha256"],
            distribution_scope=dict(sorted(raw["distribution_scope"].items())),
            maximum_download_bytes=int(limits["maximum_download_bytes"]),
            maximum_archive_members=int(limits["maximum_archive_members"]),
            maximum_license_bytes=int(limits["maximum_license_bytes"]),
            maximum_license_files=int(limits["maximum_license_files_per_component"]),
            secret_fixture_hashes=secret_fixture_hashes,
            license_reference_texts=license_reference_texts,
            python_overrides=dict(raw.get("license_overrides", {}).get("python", {})),
            npm_overrides=dict(raw.get("license_overrides", {}).get("npm", {})),
            vendored=vendored,
            source_assets=tuple(raw.get("source_assets", [])),
        )


def verify_secret_allowlist(
    repository: Path, policy: ReleasePolicy
) -> Mapping[str, Any]:
    repository = repository.resolve()
    verified = []
    for relative, expected in policy.secret_fixture_hashes.items():
        path = repository / validate_relative_path(relative)
        if not path.is_file() or path.is_symlink():
            raise ReleaseError(f"reviewed secret fixture is missing: {relative}")
        if sha256_file(path) != expected:
            raise ReleaseError(f"reviewed secret fixture bytes changed: {relative}")
        verified.append(relative)
    return {
        "fixture_count": len(verified),
        "fixtures": verified,
        "verified": True,
    }


def run_secret_scan(
    repository: Path,
    policy: ReleasePolicy,
    gitleaks: Path,
    runner: CommandRunner | None = None,
) -> Mapping[str, Any]:
    repository = repository.resolve()
    gitleaks = gitleaks.resolve()
    runner = runner or SubprocessRunner()
    fixtures = verify_secret_allowlist(repository, policy)
    version = str(runner.run((str(gitleaks), "version"), cwd=repository)).strip()
    if version != policy.gitleaks_version:
        raise ReleaseError(
            f"Gitleaks version differs from policy: {version or 'missing'}"
        )
    config = repository / "ops/owned-provider/gitleaks.toml"
    git_repository = GitRepository(repository)
    source_archive = git_repository.archive(git_repository.head(), "source/")
    with tempfile.TemporaryDirectory(prefix="owned-provider-secret-scan-") as value:
        scan_root = Path(value)
        with tarfile.open(fileobj=io.BytesIO(source_archive), mode="r:gz") as archive:
            for member in archive.getmembers():
                name = _safe_archive_name(member.name)
                if name.parts[0] != "source":
                    raise ReleaseError("secret scan archive has an unexpected root")
                relative = PurePosixPath(*name.parts[1:])
                if not relative.parts or member.isdir():
                    continue
                if not member.isfile():
                    raise ReleaseError(
                        "secret scan archive contains a non-regular path"
                    )
                stream = archive.extractfile(member)
                if stream is None:
                    raise ReleaseError("secret scan archive member is unreadable")
                write_bytes(scan_root, relative.as_posix(), stream.read())
        runner.run(
            (
                str(gitleaks),
                "dir",
                "--config",
                str(config),
                "--no-banner",
                "--redact",
                ".",
            ),
            cwd=scan_root,
        )
    runner.run(
        (
            str(gitleaks),
            "git",
            "--config",
            str(config),
            "--no-banner",
            "--redact",
            f"--log-opts={policy.integration_commit}..HEAD",
            ".",
        ),
        cwd=repository,
    )
    return {
        "fixture_count": fixtures["fixture_count"],
        "gitleaks_version": version,
        "verified": True,
    }


class ArtifactFetcher:
    def __init__(self, cache: Path, maximum_bytes: int) -> None:
        self.cache = cache.resolve()
        self.maximum_bytes = maximum_bytes
        self.cache.mkdir(parents=True, exist_ok=True)

    def fetch(self, url: str, integrity: str) -> bytes:
        parsed = urllib.parse.urlparse(url)
        if parsed.scheme != "https" or not parsed.hostname:
            raise ReleaseError(f"artifact URL is not HTTPS: {url}")
        algorithm, expected = parse_integrity(integrity)
        cache_path = self.cache / f"{algorithm}-{expected.hex()}"
        if cache_path.is_file():
            payload = cache_path.read_bytes()
            verify_integrity(payload, integrity)
            return payload
        request = urllib.request.Request(
            url,
            headers={
                "Accept-Encoding": "identity",
                "User-Agent": "owned-provider-release/1",
            },
        )
        try:
            with urllib.request.urlopen(request, timeout=60) as response:
                if response.geturl() != url:
                    redirected = urllib.parse.urlparse(response.geturl())
                    if redirected.scheme != "https":
                        raise ReleaseError("artifact redirect left HTTPS")
                payload = response.read(self.maximum_bytes + 1)
        except (OSError, urllib.error.URLError) as error:
            raise ReleaseError(f"artifact download failed: {url}: {error}") from error
        if len(payload) > self.maximum_bytes:
            raise ReleaseError(f"artifact exceeds byte limit: {url}")
        verify_integrity(payload, integrity)
        temporary = cache_path.with_name(f".{cache_path.name}.{os.getpid()}.tmp")
        temporary.write_bytes(payload)
        try:
            temporary.replace(cache_path)
        except FileExistsError:
            temporary.unlink(missing_ok=True)
        return payload


@dataclass(frozen=True)
class ArchiveMetadata:
    license_expression: str | None
    license_files: tuple[tuple[str, bytes], ...]
    package_name: str | None
    package_version: str | None
    raw_license: str | None
    classifiers: tuple[str, ...]


def _safe_archive_name(name: str) -> PurePosixPath:
    normalized = name.removeprefix("./").rstrip("/")
    if not normalized or "\\" in normalized or normalized.startswith("/"):
        raise ReleaseError(f"invalid archive path: {name!r}")
    parts: list[str] = []
    for part in PurePosixPath(normalized).parts:
        if part in {"", "."}:
            continue
        if part == "..":
            if not parts:
                raise ReleaseError(f"archive path escapes its root: {name!r}")
            parts.pop()
        else:
            parts.append(part)
    if not parts:
        raise ReleaseError(f"archive path resolves to its root: {name!r}")
    return PurePosixPath(*parts)


def _license_candidate(name: str) -> bool:
    return LICENSE_BASENAME.fullmatch(PurePosixPath(name).name) is not None


def inspect_archive(
    payload: bytes,
    *,
    maximum_members: int,
    maximum_license_bytes: int,
    maximum_license_files: int,
) -> ArchiveMetadata:
    regular: dict[str, bytes] = {}
    if payload.startswith(b"PK\x03\x04"):
        with zipfile.ZipFile(io.BytesIO(payload)) as archive:
            infos = archive.infolist()
            if len(infos) > maximum_members:
                raise ReleaseError("archive member count exceeds policy")
            for info in infos:
                path = _safe_archive_name(info.filename)
                if info.is_dir():
                    continue
                if info.file_size > maximum_license_bytes and (
                    _license_candidate(path.as_posix())
                    or path.name in {"package.json", "PKG-INFO", "METADATA"}
                ):
                    raise ReleaseError(f"metadata file is too large: {path}")
                if _license_candidate(path.as_posix()) or path.name in {
                    "package.json",
                    "PKG-INFO",
                    "METADATA",
                }:
                    regular[path.as_posix()] = archive.read(info)
    else:
        try:
            archive = tarfile.open(fileobj=io.BytesIO(payload), mode="r:*")
        except tarfile.TarError as error:
            raise ReleaseError("artifact is not a supported source archive") from error
        with archive:
            members = archive.getmembers()
            if len(members) > maximum_members:
                raise ReleaseError("archive member count exceeds policy")
            for member in members:
                path = _safe_archive_name(member.name)
                if member.issym() or member.islnk():
                    _safe_archive_name(
                        str(PurePosixPath(member.name).parent / member.linkname)
                    )
                    continue
                if not member.isfile():
                    continue
                if member.size > maximum_license_bytes and (
                    _license_candidate(path.as_posix())
                    or path.name in {"package.json", "PKG-INFO", "METADATA"}
                ):
                    raise ReleaseError(f"metadata file is too large: {path}")
                if _license_candidate(path.as_posix()) or path.name in {
                    "package.json",
                    "PKG-INFO",
                    "METADATA",
                }:
                    stream = archive.extractfile(member)
                    if stream is not None:
                        regular[path.as_posix()] = stream.read(
                            maximum_license_bytes + 1
                        )
    candidates = sorted(
        (name, value)
        for name, value in regular.items()
        if _license_candidate(name) and value.strip()
    )
    if len(candidates) > maximum_license_files:
        raise ReleaseError("archive license file count exceeds policy")
    top_package_json = regular.get("package/package.json")
    if top_package_json is not None:
        try:
            package = json.loads(top_package_json)
        except (UnicodeDecodeError, json.JSONDecodeError) as error:
            raise ReleaseError("package.json in source archive is invalid") from error
        license_value = package.get("license")
        if isinstance(license_value, dict):
            license_value = license_value.get("type")
        if isinstance(license_value, list):
            license_value = " OR ".join(
                item.get("type", "") if isinstance(item, dict) else str(item)
                for item in license_value
            )
        return ArchiveMetadata(
            license_expression=str(license_value).strip() if license_value else None,
            license_files=tuple(candidates),
            package_name=str(package.get("name")) if package.get("name") else None,
            package_version=(
                str(package.get("version")) if package.get("version") else None
            ),
            raw_license=str(license_value).strip() if license_value else None,
            classifiers=(),
        )
    metadata_payload = next(
        (
            value
            for name, value in sorted(regular.items())
            if name.endswith("/PKG-INFO") or name.endswith("/METADATA")
        ),
        None,
    )
    if metadata_payload is not None:
        message = email.parser.BytesParser().parsebytes(metadata_payload)
        expression = message.get("License-Expression")
        raw_license = message.get("License")
        return ArchiveMetadata(
            license_expression=expression.strip() if expression else None,
            license_files=tuple(candidates),
            package_name=message.get("Name"),
            package_version=message.get("Version"),
            raw_license=raw_license.strip() if raw_license else None,
            classifiers=tuple(message.get_all("Classifier", [])),
        )
    package_json = next(
        (
            value
            for name, value in sorted(regular.items())
            if name.endswith("/package.json")
        ),
        None,
    )
    if package_json is not None:
        try:
            package = json.loads(package_json)
        except (UnicodeDecodeError, json.JSONDecodeError) as error:
            raise ReleaseError("package.json in source archive is invalid") from error
        license_value = package.get("license")
        if isinstance(license_value, dict):
            license_value = license_value.get("type")
        if isinstance(license_value, list):
            license_value = " OR ".join(
                item.get("type", "") if isinstance(item, dict) else str(item)
                for item in license_value
            )
        return ArchiveMetadata(
            license_expression=str(license_value).strip() if license_value else None,
            license_files=tuple(candidates),
            package_name=str(package.get("name")) if package.get("name") else None,
            package_version=(
                str(package.get("version")) if package.get("version") else None
            ),
            raw_license=str(license_value).strip() if license_value else None,
            classifiers=(),
        )
    return ArchiveMetadata(None, tuple(candidates), None, None, None, ())


def archive_files_with_prefix(
    payload: bytes, prefix: str, *, maximum_members: int
) -> dict[str, bytes]:
    validate_relative_path(prefix.rstrip("/"))
    result: dict[str, bytes] = {}
    try:
        archive = tarfile.open(fileobj=io.BytesIO(payload), mode="r:*")
    except tarfile.TarError as error:
        raise ReleaseError("artifact is not a supported tar archive") from error
    with archive:
        members = archive.getmembers()
        if len(members) > maximum_members:
            raise ReleaseError("archive member count exceeds policy")
        for member in members:
            path = _safe_archive_name(member.name).as_posix()
            if not member.isfile() or not path.startswith(prefix):
                continue
            relative = path.removeprefix(prefix)
            validate_relative_path(relative)
            stream = archive.extractfile(member)
            if stream is None:
                raise ReleaseError(f"cannot read archive member: {path}")
            result[relative] = stream.read()
    return result


