class PublicReleaseVerifier:
    def __init__(self, policy: ReleasePolicy) -> None:
        self.policy = policy

    def verify(
        self,
        bundle: Path,
        repository: Path | None = None,
        mail_edge_repository: Path | None = None,
    ) -> Mapping[str, Any]:
        if not bundle.is_dir() or bundle.is_symlink():
            raise ReleaseError("bundle is not a regular directory")
        for path in bundle.rglob("*"):
            if path.is_symlink() or (not path.is_dir() and not path.is_file()):
                raise ReleaseError(
                    f"bundle contains an unsafe filesystem entry: {path}"
                )
        sums_path = bundle / "SHA256SUMS"
        if not sums_path.is_file():
            raise ReleaseError("SHA256SUMS is missing")
        sums_payload = sums_path.read_bytes()
        checksums = parse_checksum_manifest(sums_payload)
        actual_paths = {
            path.relative_to(bundle).as_posix()
            for path in bundle.rglob("*")
            if path.is_file() and path != sums_path
        }
        if set(checksums) != actual_paths:
            raise ReleaseError("SHA256SUMS file set differs from bundle")
        for relative, expected in checksums.items():
            if sha256_file(bundle / relative) != expected:
                raise ReleaseError(f"bundle checksum mismatch: {relative}")
        for path in bundle.rglob("*.json"):
            if path.relative_to(bundle).parts[0] == "licenses":
                continue
            raw = path.read_bytes()
            try:
                value = json.loads(raw)
            except json.JSONDecodeError as error:
                raise ReleaseError(f"invalid JSON: {path}") from error
            if raw != canonical_json(value) + b"\n":
                raise ReleaseError(f"JSON is not canonical: {path}")
        manifest = json.loads((bundle / "MANIFEST.json").read_bytes())
        if manifest.get("schema") != "owned-provider-public-release-manifest-v1":
            raise ReleaseError("manifest schema is unsupported")
        if manifest.get("claims") != {
            "legal_approval": False,
            "public_source_offer_created": False,
            "section_16_7_complete": False,
            "signatures_created": False,
        }:
            raise ReleaseError("manifest makes an unsupported release claim")
        graph = json.loads((bundle / "dependencies/graph.json").read_bytes())
        if graph.get("schema") != "owned-provider-dependency-graph-v1":
            raise ReleaseError("dependency graph schema is unsupported")
        components = graph.get("components")
        counts = graph.get("counts")
        if not isinstance(components, list) or not isinstance(counts, dict):
            raise ReleaseError("dependency graph is incomplete")
        expected_counts = {
            "mail_edge_full_lock": sum(
                item.get("ecosystem") == "mail-edge-npm" for item in components
            ),
            "mail_edge_production": sum(
                item.get("ecosystem") == "mail-edge-npm"
                and item.get("scope") == "production"
                for item in components
            ),
            "owned_provider_npm_runtime": sum(
                item.get("ecosystem") == "npm" for item in components
            ),
            "owned_provider_python_runtime": sum(
                item.get("ecosystem") == "pypi" for item in components
            ),
            "vendored": sum(
                item.get("ecosystem") == "vendored-npm" for item in components
            ),
        }
        component_total = (
            counts.get("mail_edge_full_lock", 0)
            + counts.get("owned_provider_npm_runtime", 0)
            + counts.get("owned_provider_python_runtime", 0)
            + counts.get("vendored", 0)
            + 2
        )
        if counts != expected_counts or len(components) != component_total:
            raise ReleaseError("dependency graph counts differ from components")
        if expected_counts["owned_provider_python_runtime"] != 115:
            raise ReleaseError("owned-provider Python closure differs from review")
        if expected_counts["owned_provider_npm_runtime"] != 41:
            raise ReleaseError("owned-provider npm closure differs from review")
        if expected_counts["vendored"] != 4:
            raise ReleaseError("vendored component closure differs from review")
        refs = {item["bom_ref"] for item in components}
        if len(refs) != len(components):
            raise ReleaseError("dependency component references are not unique")
        for item in components:
            if not item.get("license_expression"):
                raise ReleaseError(
                    f"component license is missing: {item.get('bom_ref')}"
                )
            if not set(item.get("dependencies", [])) <= refs:
                raise ReleaseError(
                    f"component dependency is missing: {item.get('bom_ref')}"
                )
            parse_integrity(item.get("integrity", ""))
            parsed_source = urllib.parse.urlparse(item.get("source_url", ""))
            if parsed_source.scheme != "https" or not parsed_source.hostname:
                raise ReleaseError(
                    f"component source URL is not HTTPS: {item.get('bom_ref')}"
                )
            for relative in item.get("license_paths", []):
                path = bundle / validate_relative_path(relative)
                if not path.is_file() or not path.read_bytes().strip():
                    raise ReleaseError(
                        f"component license evidence is missing: {relative}"
                    )
            source_path = item.get("source_archive_path")
            copyleft = any(
                license_id.startswith(
                    ("AGPL-", "CDDL-", "EPL-", "GPL-", "LGPL-", "MPL-")
                )
                for license_id in spdx_license_ids(item["license_expression"])
            )
            if item.get("scope") in {"runtime", "vendored", "source"} or copyleft:
                if (
                    not source_path
                    or not (bundle / validate_relative_path(source_path)).is_file()
                ):
                    raise ReleaseError(
                        f"required source archive is missing: {item.get('bom_ref')}"
                    )
            if source_path:
                verify_integrity(
                    (bundle / validate_relative_path(source_path)).read_bytes(),
                    item["integrity"],
                )
        cdx = json.loads((bundle / "sbom/bom.cdx.json").read_bytes())
        if cdx.get("bomFormat") != "CycloneDX" or cdx.get("specVersion") != "1.6":
            raise ReleaseError("CycloneDX document version is invalid")
        cdx_components = {item["bom-ref"]: item for item in cdx.get("components", [])}
        if set(cdx_components) != refs or len(cdx_components) != len(components):
            raise ReleaseError("CycloneDX components differ from dependency graph")
        cdx_dependencies = {
            item["ref"]: item.get("dependsOn", [])
            for item in cdx.get("dependencies", [])
        }
        for item in components:
            algorithm, digest = parse_integrity(item["integrity"])
            cdx_item = cdx_components[item["bom_ref"]]
            expected_scope = (
                "required"
                if item["scope"] in {"runtime", "production", "source"}
                else "excluded"
            )
            expected_properties = [
                {"name": f"owned-provider:{name}", "value": value}
                for name, value in sorted(
                    {
                        "ecosystem": item["ecosystem"],
                        "scope": item["scope"],
                        **item.get("properties", {}),
                    }.items()
                )
            ]
            if (
                cdx_item.get("name") != item["name"]
                or cdx_item.get("version") != item["version"]
                or cdx_item.get("licenses")
                != [{"expression": item["license_expression"]}]
                or cdx_item.get("hashes")
                != [
                    {
                        "alg": {"sha256": "SHA-256", "sha512": "SHA-512"}[algorithm],
                        "content": digest.hex(),
                    }
                ]
                or cdx_item.get("scope") != expected_scope
                or cdx_item.get("purl") != item["bom_ref"].split("?pnpm=", 1)[0]
                or cdx_item.get("properties") != expected_properties
                or cdx_item.get("type")
                != ("application" if item["scope"] == "source" else "library")
                or cdx_item.get("externalReferences")
                != [{"type": "distribution", "url": item["source_url"]}]
                or cdx_dependencies.get(item["bom_ref"]) != item.get("dependencies", [])
            ):
                raise ReleaseError(
                    f"CycloneDX component differs from graph: {item['bom_ref']}"
                )
        cdx_metadata = cdx.get("metadata", {}).get("component", {})
        cdx_root = cdx_components.get(cdx_metadata.get("bom-ref"))
        if cdx_root is None or any(
            cdx_metadata.get(key) != cdx_root.get(key)
            for key in ("licenses", "name", "type", "version")
        ):
            raise ReleaseError("CycloneDX root metadata differs from components")
        spdx = json.loads((bundle / "sbom/bom.spdx.json").read_bytes())
        if (
            spdx.get("spdxVersion") != "SPDX-2.3"
            or spdx.get("SPDXID") != "SPDXRef-DOCUMENT"
            or spdx.get("dataLicense") != "CC0-1.0"
            or spdx.get("name") != "simplelogin-owned-provider-public-release"
            or spdx.get("creationInfo")
            != {
                "created": "1970-01-01T00:00:00Z",
                "creators": ["Tool: owned-provider-public-release-bundle-1"],
            }
        ):
            raise ReleaseError("SPDX document differs from dependency graph")
        referenced_license_ids = sorted(
            {
                license_id
                for item in components
                for license_id in license_reference_ids(item["license_expression"])
            }
        )
        missing_license_ids = sorted(
            set(referenced_license_ids) - set(self.policy.license_reference_texts)
        )
        if missing_license_ids:
            raise ReleaseError(
                "SPDX custom license references are unreviewed: "
                + ", ".join(missing_license_ids)
            )
        for license_id in referenced_license_ids:
            path = bundle / f"licenses/custom/{safe_slug(license_id)}.txt"
            expected_text = (
                self.policy.license_reference_texts[license_id].strip().encode() + b"\n"
            )
            if not path.is_file() or path.read_bytes() != expected_text:
                raise ReleaseError(
                    f"custom license evidence differs from policy: {license_id}"
                )
        expected_extracted_licenses = [
            {
                "extractedText": self.policy.license_reference_texts[license_id].strip()
                + "\n",
                "licenseId": license_id,
            }
            for license_id in referenced_license_ids
        ]
        if spdx.get("hasExtractedLicensingInfos") != expected_extracted_licenses:
            raise ReleaseError("SPDX custom license evidence differs from policy")
        spdx_components = {}
        for item in spdx.get("packages", []):
            source_info = item.get("sourceInfo", "")
            prefix = "owned-provider-bom-ref: "
            if not source_info.startswith(prefix):
                raise ReleaseError("SPDX package lacks dependency graph linkage")
            bom_ref = source_info.removeprefix(prefix)
            if bom_ref in spdx_components:
                raise ReleaseError("SPDX dependency graph linkage is duplicated")
            spdx_components[bom_ref] = item
        if set(spdx_components) != refs:
            raise ReleaseError("SPDX packages differ from dependency graph")
        spdx_ids = {
            bom_ref: item["SPDXID"] for bom_ref, item in spdx_components.items()
        }
        expected_relationships = {
            (spdx_ids[item["bom_ref"]], spdx_ids[dependency], "DEPENDS_ON")
            for item in components
            for dependency in item.get("dependencies", [])
        }
        observed_relationships = {
            (
                item.get("spdxElementId"),
                item.get("relatedSpdxElement"),
                item.get("relationshipType"),
            )
            for item in spdx.get("relationships", [])
        }
        if observed_relationships != expected_relationships:
            raise ReleaseError("SPDX relationships differ from dependency graph")
        for item in components:
            algorithm, digest = parse_integrity(item["integrity"])
            spdx_item = spdx_components[item["bom_ref"]]
            if (
                spdx_item.get("name") != item["name"]
                or spdx_item.get("versionInfo") != item["version"]
                or spdx_item.get("downloadLocation") != item["source_url"]
                or spdx_item.get("licenseConcluded") != item["license_expression"]
                or spdx_item.get("licenseDeclared") != item["license_expression"]
                or spdx_item.get("filesAnalyzed") is not False
                or spdx_item.get("sourceInfo")
                != f"owned-provider-bom-ref: {item['bom_ref']}"
                or spdx_item.get("externalRefs")
                != [
                    {
                        "referenceCategory": "PACKAGE-MANAGER",
                        "referenceLocator": item["bom_ref"].split("?pnpm=", 1)[0],
                        "referenceType": "purl",
                    }
                ]
                or spdx_item.get("checksums")
                != [
                    {
                        "algorithm": algorithm.upper(),
                        "checksumValue": digest.hex(),
                    }
                ]
            ):
                raise ReleaseError(
                    f"SPDX package differs from graph: {item['bom_ref']}"
                )
        provenance = json.loads((bundle / "PROVENANCE.json").read_bytes())
        if provenance.get("bundle_format") != self.policy.format_name:
            raise ReleaseError("bundle provenance format differs from policy")
        if provenance.get("distribution_scope") != dict(self.policy.distribution_scope):
            raise ReleaseError("distribution scope differs from policy")
        container = json.loads(
            (bundle / "evidence/container-runtime.json").read_bytes()
        )
        runtime = container.get("runtime", {})
        completeness = (
            "debian_scan_complete",
            "executable_scan_complete",
            "native_scan_complete",
            "npm_scan_complete",
            "python_scan_complete",
        )
        if any(runtime.get(name) is not True for name in completeness):
            raise ReleaseError("container inspection is incomplete")
        debian_license_paths = runtime.get("debian_license_paths")
        if not isinstance(debian_license_paths, list) or not debian_license_paths:
            raise ReleaseError("container Debian license evidence is incomplete")
        for relative in debian_license_paths:
            path = bundle / validate_relative_path(relative)
            if not path.is_file() or not path.read_bytes().strip():
                raise ReleaseError(
                    f"container Debian license evidence is missing: {relative}"
                )
        source_archives = manifest.get("source_archives", {})
        if set(source_archives) != {"mail_edge", "owned_provider"}:
            raise ReleaseError("source archive set differs from policy")
        for record in source_archives.values():
            path = bundle / validate_relative_path(record["path"])
            if sha256_file(path) != record["sha256"]:
                raise ReleaseError("source archive hash differs from manifest")
            with tarfile.open(path, mode="r:gz") as archive:
                names = [member.name for member in archive.getmembers()]
                if any(
                    "/.git/" in name or name.endswith("/static/vendor/paddle.js")
                    for name in names
                ):
                    raise ReleaseError("source archive contains a prohibited path")
        static_audit = json.loads(
            (bundle / "dependencies/static-assets.json").read_bytes()
        )
        if static_audit.get("schema") != "owned-provider-static-asset-audit-v1":
            raise ReleaseError("static asset audit schema is unsupported")
        expected_tabler = {
            "exact_file_count": 477,
            "local_file_count": 481,
            "local_only": [
                "js/vendors/base64.js",
                "js/vendors/bootstrap.bundle.min.js.map",
                "js/vendors/webauthn.js",
            ],
            "modified": ["js/core.js"],
            "upstream_file_count": 478,
            "upstream_only": [],
        }
        if static_audit.get("tabler") != expected_tabler:
            raise ReleaseError("static Tabler asset relationship differs from review")
        owned_record = source_archives["owned_provider"]
        owned_files = archive_files_with_prefix(
            (bundle / validate_relative_path(owned_record["path"])).read_bytes(),
            f"owned-provider-{manifest['owned_provider_commit']}/",
            maximum_members=self.policy.maximum_archive_members,
        )
        clipboard = static_audit.get("clipboard")
        clipboard_path = "static/vendor/clipboard.min.js"
        if (
            not isinstance(clipboard, dict)
            or clipboard.get("exact") is not True
            or clipboard.get("path") != clipboard_path
            or clipboard_path not in owned_files
            or clipboard.get("sha256")
            != sha256_bytes(owned_files.get(clipboard_path, b""))
        ):
            raise ReleaseError("static clipboard evidence differs from source archive")
        reviewed_assets = {item["name"]: item for item in self.policy.source_assets}
        observed_assets = static_audit.get("source_assets")
        if not isinstance(observed_assets, list) or {
            item.get("name") for item in observed_assets if isinstance(item, dict)
        } != set(reviewed_assets):
            raise ReleaseError("reviewed source asset set differs from policy")
        for record in observed_assets:
            reviewed = reviewed_assets[record["name"]]
            if any(
                record.get(key) != reviewed[key]
                for key in ("license_expression", "relationship", "source_url")
            ):
                raise ReleaseError("source asset metadata differs from policy")
            paths = record.get("paths")
            if not isinstance(paths, list) or {
                item.get("path") for item in paths if isinstance(item, dict)
            } != set(reviewed["paths"]):
                raise ReleaseError("source asset paths differ from policy")
            for item in paths:
                relative = validate_relative_path(item["path"]).as_posix()
                if relative not in owned_files or item.get("sha256") != sha256_bytes(
                    owned_files.get(relative, b"")
                ):
                    raise ReleaseError(
                        f"source asset hash differs from source archive: {relative}"
                    )
        if repository is not None:
            repository = repository.resolve()
            if (
                sha256_file(repository / "uv.lock")
                != graph["lock_sha256"]["owned_provider_uv"]
            ):
                raise ReleaseError("bundle is stale for the owned-provider uv.lock")
            if (
                sha256_file(repository / "static/package-lock.json")
                != graph["lock_sha256"]["owned_provider_npm"]
            ):
                raise ReleaseError("bundle is stale for the owned-provider npm lock")
            if GitRepository(repository).head() != manifest["owned_provider_commit"]:
                raise ReleaseError("bundle is stale for the owned-provider commit")
        if mail_edge_repository is not None:
            edge = GitRepository(mail_edge_repository.resolve())
            payload = edge.git(
                "show", f"{manifest['mail_edge_commit']}:pnpm-lock.yaml", text=False
            )
            assert isinstance(payload, bytes)
            if sha256_bytes(payload) != graph["lock_sha256"]["mail_edge_pnpm"]:
                raise ReleaseError("bundle is stale for the Mail Edge lock")
        return {
            "bundle": str(bundle.resolve()),
            "component_count": len(components),
            "file_count": len(checksums) + 1,
            "mail_edge_commit": manifest["mail_edge_commit"],
            "owned_provider_commit": manifest["owned_provider_commit"],
            "verified": True,
        }


def ensure_spdx_repository(cache: Path, policy: ReleasePolicy) -> Path:
    destination = cache.resolve() / "spdx-license-list-data.git"
    runner = SubprocessRunner()
    if not destination.exists():
        destination.mkdir(parents=True)
        runner.run(("git", "init", "--bare"), cwd=destination)
        runner.run(
            ("git", "remote", "add", "origin", policy.spdx_origin), cwd=destination
        )
    repository = GitRepository(destination, runner)
    if repository.origin() != policy.spdx_origin:
        raise ReleaseError("cached SPDX repository has the wrong origin")
    runner.run(
        (
            "git",
            "fetch",
            "--quiet",
            "--force",
            "origin",
            f"refs/tags/{policy.spdx_tag}:refs/tags/{policy.spdx_tag}",
        ),
        cwd=destination,
    )
    actual = str(
        repository.git("rev-parse", f"refs/tags/{policy.spdx_tag}^{{commit}}")
    ).strip()
    if actual != policy.spdx_commit:
        raise ReleaseError("cached SPDX tag differs from policy")
    return destination


def main() -> None:
    script_directory = Path(__file__).resolve().parent
    default_policy = script_directory.parent / "public-release-policy.toml"
    parser = argparse.ArgumentParser()
    parser.add_argument("--policy", type=Path, default=default_policy)
    commands = parser.add_subparsers(dest="command", required=True)
    generate = commands.add_parser("generate")
    generate.add_argument("--repository", type=Path, required=True)
    generate.add_argument("--mail-edge-repository", type=Path, required=True)
    generate.add_argument("--mail-edge-commit")
    generate.add_argument("--spdx-repository", type=Path)
    generate.add_argument("--image", required=True)
    generate.add_argument("--cache", type=Path, required=True)
    generate.add_argument("--output", type=Path, required=True)
    verify = commands.add_parser("verify")
    verify.add_argument("--bundle", type=Path, required=True)
    verify.add_argument("--repository", type=Path)
    verify.add_argument("--mail-edge-repository", type=Path)
    secret_fixtures = commands.add_parser("secret-fixtures")
    secret_fixtures.add_argument("--repository", type=Path, required=True)
    secret_scan = commands.add_parser("secret-scan")
    secret_scan.add_argument("--repository", type=Path, required=True)
    secret_scan.add_argument("--gitleaks", type=Path, required=True)
    args = parser.parse_args()
    policy = ReleasePolicy.load(args.policy)
    if args.command == "generate":
        repository = args.repository.resolve()
        mail_edge_commit = args.mail_edge_commit
        if mail_edge_commit is None:
            mail_edge_commit = (
                (repository / policy.mail_edge_commit_file).read_text().strip()
            )
        spdx_repository = args.spdx_repository
        if spdx_repository is None:
            spdx_repository = ensure_spdx_repository(args.cache, policy)
        fetcher = ArtifactFetcher(
            args.cache / "artifacts", policy.maximum_download_bytes
        )
        directory, archive = PublicReleaseBuilder(policy, fetcher).build(
            repository,
            args.mail_edge_repository.resolve(),
            spdx_repository.resolve(),
            mail_edge_commit,
            args.output.resolve(),
            args.image,
        )
        result = PublicReleaseVerifier(policy).verify(
            directory, repository, args.mail_edge_repository.resolve()
        )
        print(
            canonical_json(
                {
                    **result,
                    "archive": str(archive),
                    "archive_sha256": sha256_file(archive),
                    "bundle_sha256sums_sha256": sha256_file(directory / "SHA256SUMS"),
                }
            ).decode(),
            end="",
        )
    elif args.command == "verify":
        result = PublicReleaseVerifier(policy).verify(
            args.bundle.resolve(), args.repository, args.mail_edge_repository
        )
        print(canonical_json(result).decode(), end="")
    elif args.command == "secret-fixtures":
        result = verify_secret_allowlist(args.repository, policy)
        print(canonical_json(result).decode(), end="")
    else:
        result = run_secret_scan(args.repository, policy, args.gitleaks)
        print(canonical_json(result).decode(), end="")


