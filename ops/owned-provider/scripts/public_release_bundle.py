def read_runtime_python(path: Path) -> tuple[str, ...]:
    values = tuple(
        line.strip().lower()
        for line in path.read_text(encoding="utf-8").splitlines()
        if line.strip() and not line.startswith("#")
    )
    if len(values) != 115 or len(set(values)) != len(values):
        raise ReleaseError(
            "reviewed Python runtime inventory must contain 115 packages"
        )
    return values


def python_components(repository: Path) -> tuple[Component, ...]:
    with (repository / "uv.lock").open("rb") as stream:
        lock = tomllib.load(stream)
    packages = {
        (normalized_name(item["name"]), str(item["version"])): item
        for item in lock["package"]
        if "version" in item and item.get("source", {}).get("registry")
    }
    runtime = read_runtime_python(repository / "ops/owned-provider/runtime-python.txt")
    refs = {
        entry: f"pkg:pypi/{entry.split('==', 1)[0]}@{entry.split('==', 1)[1]}"
        for entry in runtime
    }
    runtime_by_name = {
        normalized_name(entry.split("==", 1)[0]): entry for entry in runtime
    }
    components = []
    for entry in runtime:
        name, version = entry.split("==", 1)
        item = packages.get((normalized_name(name), version))
        if item is None or "sdist" not in item:
            raise ReleaseError(
                f"reviewed Python package is stale or lacks sdist: {entry}"
            )
        sdist = item["sdist"]
        digest = str(sdist["hash"])
        if not digest.startswith("sha256:") or SHA256.fullmatch(digest[7:]) is None:
            raise ReleaseError(f"Python sdist has an invalid hash: {entry}")
        dependencies = tuple(
            sorted(
                refs[runtime_by_name[normalized_name(dep["name"])]]
                for dep in item.get("dependencies", [])
                if normalized_name(dep["name"]) in runtime_by_name
            )
        )
        components.append(
            Component(
                bom_ref=refs[entry],
                ecosystem="pypi",
                name=name,
                version=version,
                scope="runtime",
                license_expression="",
                license_evidence="",
                source_url=sdist["url"],
                integrity=f"sha256-{base64.b64encode(bytes.fromhex(digest[7:])).decode()}",
                dependencies=dependencies,
                properties={"target": "cpython-3.12-linux-x86_64"},
            )
        )
    return tuple(sorted(components, key=lambda value: value.bom_ref))


def npm_lock_components(repository: Path) -> tuple[Component, ...]:
    lock = json.loads((repository / "static/package-lock.json").read_text())
    packages: Mapping[str, Any] = lock["packages"]

    def resolve_path(parent: str, name: str) -> str | None:
        base = parent
        while True:
            candidate = f"{base}/node_modules/{name}"
            if candidate in packages:
                return candidate
            base, separator, _ = base.rpartition("/node_modules/")
            if not separator:
                candidate = f"node_modules/{name}"
                return candidate if candidate in packages else None

    def installed_dependencies(path: str, item: Mapping[str, Any]) -> set[str]:
        resolved = set()
        for dependency_kind in ("dependencies", "optionalDependencies"):
            for name in item.get(dependency_kind, {}):
                target = resolve_path(path, name)
                if target is None:
                    if dependency_kind == "dependencies":
                        raise ReleaseError(
                            f"required npm dependency is absent from lock: {path} -> {name}"
                        )
                    continue
                resolved.add(target)
        peer_metadata = item.get("peerDependenciesMeta", {})
        for name in item.get("peerDependencies", {}):
            target = resolve_path(path, name)
            if target is None:
                if not peer_metadata.get(name, {}).get("optional", False):
                    raise ReleaseError(
                        f"required npm peer dependency is absent from lock: {path} -> {name}"
                    )
                continue
            resolved.add(target)
        return resolved

    roots = set(packages[""]["dependencies"])
    reachable: set[str] = set()
    pending = [f"node_modules/{name}" for name in sorted(roots)]
    while pending:
        path = pending.pop()
        if path in reachable:
            continue
        item = packages.get(path)
        if item is None or item.get("dev") is True:
            raise ReleaseError(
                f"npm production dependency is absent or dev-only: {path}"
            )
        reachable.add(path)
        pending.extend(sorted(installed_dependencies(path, item)))
    refs = {
        path: f"pkg:npm/{urllib.parse.quote(path.rsplit('node_modules/', 1)[1], safe='@')}@{packages[path]['version']}"
        for path in reachable
    }
    components = []
    for path in sorted(reachable):
        item = packages[path]
        name = path.rsplit("node_modules/", 1)[1]
        dependencies = tuple(
            sorted(
                refs[dependency] for dependency in installed_dependencies(path, item)
            )
        )
        components.append(
            Component(
                bom_ref=refs[path],
                ecosystem="npm",
                name=name,
                version=str(item["version"]),
                scope="runtime",
                license_expression="",
                license_evidence="",
                source_url=item["resolved"],
                integrity=item["integrity"],
                dependencies=dependencies,
                properties={"lock_path": path},
            )
        )
    if len(components) != 41:
        raise ReleaseError(
            f"npm production closure changed: expected 41, got {len(components)}"
        )
    return tuple(components)


def _yaml_scalar(value: str) -> str:
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in {"'", '"'}:
        if value[0] == "'":
            return value[1:-1].replace("''", "'")
        return json.loads(value)
    return value


def _pnpm_identity(snapshot_key: str) -> tuple[str, str]:
    base = snapshot_key.split("(", 1)[0]
    name, separator, version = base.rpartition("@")
    if not separator or not name or not version:
        raise ReleaseError(f"invalid pnpm package key: {snapshot_key}")
    return name, version


@dataclass(frozen=True)
class PnpmGraph:
    components: tuple[Component, ...]
    production_refs: frozenset[str]
    root_dependencies: tuple[str, ...]
    lock_sha256: str


def parse_pnpm_lock(
    payload: bytes,
    *,
    expected_full_count: int | None = None,
    expected_production_count: int | None = None,
) -> PnpmGraph:
    try:
        lines = payload.decode("utf-8").splitlines()
    except UnicodeDecodeError as error:
        raise ReleaseError("pnpm lock is not UTF-8") from error
    section = ""
    current = ""
    subsection = ""
    packages: dict[str, str] = {}
    snapshots: dict[str, dict[str, str]] = {}
    importer_roots: list[tuple[str, str]] = []
    importer_category = ""
    importer_dependency = ""
    for line in lines:
        if line and not line.startswith(" ") and line.endswith(":"):
            section = line[:-1]
            current = subsection = importer_category = importer_dependency = ""
            continue
        if section == "packages":
            match = re.match(r"^  ([^ ].*):$", line)
            if match:
                current = _yaml_scalar(match.group(1))
                continue
            if current:
                match = re.match(r"^    resolution: \{integrity: ([^}]+)\}$", line)
                if match:
                    packages[current] = _yaml_scalar(match.group(1))
        elif section == "snapshots":
            match = re.match(r"^  ([^ ].*):(?: \{\})?$", line)
            if match:
                current = _yaml_scalar(match.group(1))
                snapshots.setdefault(current, {})
                subsection = ""
                continue
            match = re.match(r"^    (dependencies|optionalDependencies):$", line)
            if match:
                subsection = match.group(1)
                continue
            match = re.match(r"^      (.+): (.+)$", line)
            if current and subsection and match:
                snapshots[current][_yaml_scalar(match.group(1))] = _yaml_scalar(
                    match.group(2)
                )
        elif section == "importers":
            match = re.match(r"^  ([^ ].*):$", line)
            if match:
                current = _yaml_scalar(match.group(1))
                importer_category = importer_dependency = ""
                continue
            match = re.match(
                r"^    (dependencies|optionalDependencies|devDependencies):$", line
            )
            if match:
                importer_category = match.group(1)
                importer_dependency = ""
                continue
            match = re.match(r"^      (.+):$", line)
            if match and importer_category:
                importer_dependency = _yaml_scalar(match.group(1))
                continue
            match = re.match(r"^        version: (.+)$", line)
            if (
                match
                and importer_category in {"dependencies", "optionalDependencies"}
                and importer_dependency
            ):
                version = _yaml_scalar(match.group(1))
                if not version.startswith("link:"):
                    importer_roots.append((importer_dependency, version))
    if set(packages) != {key.split("(", 1)[0] for key in snapshots}:
        raise ReleaseError("Mail Edge package and snapshot identities differ")
    if expected_full_count is not None and (
        len(packages) != expected_full_count or len(snapshots) != expected_full_count
    ):
        raise ReleaseError(
            "Mail Edge lock changed: expected "
            f"{expected_full_count} package and snapshot records, "
            f"got {len(packages)} and {len(snapshots)}"
        )
    missing_packages = sorted(
        key for key in snapshots if key.split("(", 1)[0] not in packages
    )
    if missing_packages:
        raise ReleaseError(
            f"pnpm snapshots lack package metadata: {missing_packages[:10]}"
        )

    def resolve(name: str, version: str) -> str:
        alias = version.removeprefix("npm:")
        if "@" in alias and not re.match(r"^[0-9v]", alias):
            alias_name, separator, alias_version = alias.rpartition("@")
            if separator and alias_name and alias_version:
                name, version = alias_name, alias_version
        direct = f"{name}@{version}"
        if direct in snapshots:
            return direct
        base = version.split("(", 1)[0]
        matches = sorted(
            key
            for key in snapshots
            if key == f"{name}@{base}" or key.startswith(f"{name}@{base}(")
        )
        if len(matches) != 1:
            raise ReleaseError(f"pnpm edge is missing or ambiguous: {name}@{version}")
        return matches[0]

    refs = {
        key: f"pkg:npm/{urllib.parse.quote(_pnpm_identity(key)[0], safe='@')}@{_pnpm_identity(key)[1]}?pnpm={urllib.parse.quote(key, safe='')}"
        for key in snapshots
    }
    edges: dict[str, tuple[str, ...]] = {}
    for key, dependencies in snapshots.items():
        edges[key] = tuple(
            sorted(
                refs[resolve(name, version)] for name, version in dependencies.items()
            )
        )
    root_keys = tuple(
        sorted({resolve(name, version) for name, version in importer_roots})
    )
    production_keys: set[str] = set()
    pending = list(root_keys)
    reverse_refs = {value: key for key, value in refs.items()}
    while pending:
        key = pending.pop()
        if key in production_keys:
            continue
        production_keys.add(key)
        pending.extend(reverse_refs[ref] for ref in edges[key])
    components = []
    for key in sorted(snapshots):
        name, version = _pnpm_identity(key)
        integrity = packages[key.split("(", 1)[0]]
        parse_integrity(integrity)
        components.append(
            Component(
                bom_ref=refs[key],
                ecosystem="mail-edge-npm",
                name=name,
                version=version,
                scope="production" if key in production_keys else "build",
                license_expression="",
                license_evidence="",
                source_url=npm_archive_url(name, version),
                integrity=integrity,
                dependencies=edges[key],
                properties={"pnpm_snapshot_key": key},
            )
        )
    production_refs = frozenset(refs[key] for key in production_keys)
    if (
        expected_production_count is not None
        and len(production_refs) != expected_production_count
    ):
        raise ReleaseError(
            "Mail Edge production closure changed: expected "
            f"{expected_production_count}, got {len(production_refs)}"
        )
    return PnpmGraph(
        components=tuple(components),
        production_refs=production_refs,
        root_dependencies=tuple(sorted(refs[key] for key in root_keys)),
        lock_sha256=sha256_bytes(payload),
    )


def write_bytes(root: Path, relative: str, payload: bytes, mode: int = 0o644) -> None:
    path = root / validate_relative_path(relative)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(payload)
    path.chmod(mode)


def copy_license_files(
    root: Path, component: Component, metadata: ArchiveMetadata
) -> tuple[str, ...]:
    paths = []
    prefix = f"licenses/packages/{safe_slug(component.ecosystem)}/{safe_slug(component.name)}@{safe_slug(component.version)}"
    seen: set[str] = set()
    for archive_name, payload in metadata.license_files:
        basename = PurePosixPath(archive_name).name
        candidate = f"{prefix}/{safe_slug(basename)}"
        if candidate in seen:
            candidate = f"{prefix}/{sha256_bytes(archive_name.encode())[:12]}-{safe_slug(basename)}"
        seen.add(candidate)
        write_bytes(root, candidate, payload)
        paths.append(candidate)
    return tuple(sorted(paths))


def copy_custom_license_references(
    root: Path,
    component: Component,
    metadata: ArchiveMetadata,
    license_reference_texts: Mapping[str, str],
) -> tuple[str, ...]:
    paths = []
    evidence = tuple(
        payload.replace(b"\r\n", b"\n") for _, payload in metadata.license_files
    )
    for license_id in license_reference_ids(component.license_expression):
        license_text = license_reference_texts.get(license_id)
        if license_text is None:
            raise ReleaseError(f"custom license reference is unreviewed: {license_id}")
        payload = license_text.strip().encode() + b"\n"
        if not any(payload.strip() in candidate for candidate in evidence):
            raise ReleaseError(
                f"custom license reference differs from archive evidence: {component.bom_ref}"
            )
        path = f"licenses/custom/{safe_slug(license_id)}.txt"
        write_bytes(root, path, payload)
        paths.append(path)
    return tuple(paths)


