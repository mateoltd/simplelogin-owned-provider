def normalize_declared_license(value: str) -> str | None:
    raw = value.strip()
    legacy = LEGACY_LICENSES.get(raw.lower())
    if legacy:
        return legacy
    if len(raw) > 256 or re.fullmatch(r"[A-Za-z0-9.+() -]+", raw) is None:
        return None
    tokens = spdx_license_ids(raw)
    if not tokens or any(
        token.lower() in {"unknown", "unlicensed"} for token in tokens
    ):
        return None
    if all(
        "-" not in token and token not in {"0BSD", "MIT", "ISC", "Unlicense", "Zlib"}
        for token in tokens
    ):
        return None
    return raw


def resolve_license(
    ecosystem: str,
    name: str,
    version: str,
    metadata: ArchiveMetadata,
    overrides: Mapping[str, str],
) -> tuple[str, str]:
    key = f"{normalized_name(name)}@{version}"
    override = overrides.get(key) or overrides.get(f"{name}@{version}")
    if override:
        declared = None
        for value in (metadata.license_expression, metadata.raw_license):
            if value and (normalized := normalize_declared_license(value)):
                declared = normalized
                break
        classifier_values = {
            CLASSIFIER_LICENSES[classifier]
            for classifier in metadata.classifiers
            if classifier in CLASSIFIER_LICENSES
        }
        if declared is None and len(classifier_values) == 1:
            declared = next(iter(classifier_values))
        if declared and set(spdx_license_ids(declared)).isdisjoint(
            spdx_license_ids(override)
        ):
            raise ReleaseError(
                f"reviewed license override conflicts with archive metadata: {name}@{version}"
            )
        return override, "reviewed-policy-override"
    if metadata.license_expression:
        normalized = normalize_declared_license(metadata.license_expression)
        if normalized:
            return normalized, "archive-metadata"
    classifier_values = sorted(
        {
            CLASSIFIER_LICENSES[classifier]
            for classifier in metadata.classifiers
            if classifier in CLASSIFIER_LICENSES
        }
    )
    if len(classifier_values) == 1:
        return classifier_values[0], "archive-classifier"
    if metadata.raw_license:
        normalized = normalize_declared_license(metadata.raw_license)
        if normalized:
            return normalized, "archive-license-field"
    raise ReleaseError(
        f"{ecosystem} package has no unambiguous reviewed license: {name}@{version}"
    )


def spdx_license_ids(expression: str) -> tuple[str, ...]:
    values = []
    for token in SPDX_TOKEN.findall(expression):
        if token in LICENSE_OPERATORS or token.startswith("LicenseRef-"):
            continue
        if token.endswith("+"):
            token = token[:-1]
        values.append(token)
    return tuple(sorted(set(values)))


def license_reference_ids(expression: str) -> tuple[str, ...]:
    return tuple(
        sorted(
            {
                token
                for token in SPDX_TOKEN.findall(expression)
                if token.startswith("LicenseRef-")
            }
        )
    )


